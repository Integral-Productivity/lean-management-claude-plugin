// Tests for the generated A3 index (plan R10, R11).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { loadA3s, renderIndex } from './a3-index.mjs';

const header = (id, title, stage, nextReview) => `---
format: a3/v1
a3_id: ${id}
title: ${title}
owner: Billing lead
holder: Billing lead
holder_type: human
coach: Operations coach
stage: ${stage}
opened: ${id.slice(3, 13)}
next_review: ${nextReview}
revision: A
tracker: null
---

# ${title}
`;

function repo(files) {
  const root = mkdtempSync(join(tmpdir(), 'a3-index-'));
  mkdirSync(join(root, 'docs/a3'), { recursive: true });
  writeFileSync(join(root, 'docs/a3/README.md'), '# A3s\n');
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, 'docs/a3', name), text);
  return root;
}

test('loadA3s reads each A3 header in docs/a3 and skips README and files that are not A3s', () => {
  const root = repo({
    'A3-2026-10-28-late-invoices.md': header('A3-2026-10-28-late-invoices', 'Invoices reach customers late', 'do', '2026-11-11'),
    'notes.md': '# not an A3\n',
  });
  const found = loadA3s(root, 'example/billing');
  assert.equal(found.length, 1);
  assert.deepEqual(found[0], {
    a3Id: 'A3-2026-10-28-late-invoices',
    repo: 'example/billing',
    path: 'docs/a3/A3-2026-10-28-late-invoices.md',
    title: 'Invoices reach customers late',
    owner: 'Billing lead',
    stage: 'do',
    nextReview: '2026-11-11',
  });
});

test('renderIndex lists ID, repository, title, owner, stage, and next review, open A3s first by review date (R10)', () => {
  const rows = [
    { a3Id: 'A3-2026-01-02-b', repo: 'example/b', path: 'docs/a3/A3-2026-01-02-b.md', title: 'B', owner: 'O', stage: 'closed', nextReview: null },
    { a3Id: 'A3-2026-01-03-c', repo: 'example/c', path: 'docs/a3/A3-2026-01-03-c.md', title: 'C | pipe', owner: 'O', stage: 'do', nextReview: '2026-02-01' },
    { a3Id: 'A3-2026-01-01-a', repo: 'example/a', path: 'docs/a3/A3-2026-01-01-a.md', title: 'A', owner: 'O', stage: 'plan', nextReview: '2026-01-20' },
  ];
  const md = renderIndex(rows, { generated: '2026-01-05' });
  assert.match(md, /Generated by scripts\/a3-index\.mjs on 2026-01-05\. Do not edit by hand\./);
  assert.match(md, /\| A3 ID \| Repository \| Title \| Owner \| Stage \| Next review \|/);
  const order = ['A3-2026-01-01-a', 'A3-2026-01-03-c', 'A3-2026-01-02-b'].map((id) => md.indexOf(`[${id}]`));
  assert.deepEqual([...order].sort((x, y) => x - y), order);
  assert.match(md, /\[A3-2026-01-01-a\]\(https:\/\/github\.com\/example\/a\/blob\/HEAD\/docs\/a3\/A3-2026-01-01-a\.md\)/);
  assert.match(md, /C \\\| pipe/);
  assert.match(md, /\| closed \| - \|/);
});

test('the command indexes several repositories into one file', () => {
  const a = repo({ 'A3-2026-10-28-late-invoices.md': header('A3-2026-10-28-late-invoices', 'Invoices reach customers late', 'do', '2026-11-11') });
  const b = repo({ 'A3-2026-10-29-slow-onboarding.md': header('A3-2026-10-29-slow-onboarding', 'Onboarding takes too long', 'plan', '2026-11-05') });
  const out = join(a, 'index.md');
  const script = fileURLToPath(new URL('./a3-index.mjs', import.meta.url));
  execFileSync('node', [script, '--repo', `example/billing=${a}`, '--repo', `example/people=${b}`, '--out', out, '--generated', '2026-10-30']);
  const md = readFileSync(out, 'utf8');
  assert.match(md, /example\/billing/);
  assert.match(md, /example\/people/);
  assert.ok(md.indexOf('A3-2026-10-29-slow-onboarding') < md.indexOf('A3-2026-10-28-late-invoices'));
});
