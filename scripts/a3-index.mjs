#!/usr/bin/env node
// Generated A3 index (plan R10, R11): one table of every A3 in the given repositories,
// built from the headers. The caller decides which repositories to index; this plugin
// names none of them.
//
// Usage:
//   node scripts/a3-index.mjs --repo owner/name=path [--repo ...] [--out file] [--generated YYYY-MM-DD]
// Each path is a local checkout; the script reads <path>/docs/a3/*.md. Without --out it prints.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FORMAT, STAGES, parseFrontMatter } from './check-a3.mjs';

export const A3_DIR = 'docs/a3';

export function loadA3s(root, repo) {
  const dir = join(root, A3_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md' && f !== 'index.md')
    .sort()
    .flatMap((f) => {
      const fm = parseFrontMatter(readFileSync(join(dir, f), 'utf8'));
      if (!fm || fm.data.format !== FORMAT) return [];
      const d = fm.data;
      return [{ a3Id: d.a3_id, repo, path: `${A3_DIR}/${f}`, title: d.title, owner: d.owner, stage: d.stage, nextReview: d.next_review ?? null }];
    });
}

const cell = (v) => String(v ?? '-').replace(/\|/g, '\\|');

// Open A3s first, soonest review first; closed A3s last. Ties break on the ID.
function order(a, b) {
  const closed = (r) => (r.stage === 'closed' ? 1 : 0);
  return closed(a) - closed(b) || (a.nextReview ?? '9999').localeCompare(b.nextReview ?? '9999') || a.a3Id.localeCompare(b.a3Id);
}

export function renderIndex(rows, { generated }) {
  const lines = [
    '# A3 index',
    '',
    `Generated by scripts/a3-index.mjs on ${generated}. Do not edit by hand.`,
    `${rows.length} A3(s). Stages: ${STAGES.join(', ')}.`,
    '',
    '| A3 ID | Repository | Title | Owner | Stage | Next review |',
    '|-------|------------|-------|-------|-------|-------------|',
    ...[...rows].sort(order).map((r) =>
      `| [${r.a3Id}](https://github.com/${r.repo}/blob/HEAD/${r.path}) | ${cell(r.repo)} | ${cell(r.title)} | ${cell(r.owner)} | ${cell(r.stage)} | ${cell(r.nextReview)} |`),
  ];
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const repos = [];
  let out = null;
  let generated = new Date().toISOString().slice(0, 10);
  for (let i = 0; i < args.length; i += 1) {
    if (args[i] === '--repo') repos.push(args[++i]);
    else if (args[i] === '--out') out = args[++i];
    else if (args[i] === '--generated') generated = args[++i];
    else {
      console.error(`unknown argument ${args[i]} (see the header of this file)`);
      process.exit(2);
    }
  }
  if (repos.length === 0) {
    console.error('give at least one --repo owner/name=path');
    process.exit(2);
  }
  const rows = repos.flatMap((spec) => {
    const at = spec.indexOf('=');
    if (at < 1) throw new Error(`--repo ${spec} must look like owner/name=path`);
    return loadA3s(spec.slice(at + 1), spec.slice(0, at));
  });
  const md = renderIndex(rows, { generated });
  if (out) {
    writeFileSync(out, md);
    console.log(`${out}: ${rows.length} A3(s) from ${repos.length} repositor${repos.length === 1 ? 'y' : 'ies'}.`);
  } else {
    process.stdout.write(md);
  }
}
